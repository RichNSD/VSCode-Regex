/**
 * Generates the TextMate grammars in syntaxes/ from the Sublime Text
 * definitions in sublime/.
 *
 * VS Code and Sublime both use Oniguruma, so patterns carry over unchanged.
 * The two formats differ in how they nest contexts: TextMate only has
 * begin/end rules, while Sublime can also `set` (replace) contexts and push
 * several at once.
 *
 * - The JavaScript and Python syntaxes only push a context that ends with a
 *   single `pop` rule, which is exactly a TextMate begin/end rule, so they are
 *   converted mechanically (`convertSyntax`).
 * - RegExp.sublime-syntax (PCRE) uses `set` throughout, so it is ported rule by
 *   rule (`pcreGrammar`), keeping its patterns, scopes and rule order. Its
 *   "unexpected quantifier" contexts, which Sublime pushes after a token, become
 *   an extra capture on that token's pattern.
 *
 * Run with --check to verify the committed grammars are up to date.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readSyntax = (file) => JSON.parse(fs.readFileSync(path.join(root, "sublime", file), "utf8"));

export const GRAMMARS = [
	{
		file: "regexp.tmLanguage.json",
		source: "RegExp.sublime-syntax.json",
		build: (syntax) => pcreGrammar(syntax),
	},
	{
		file: "regexp-javascript.tmLanguage.json",
		source: "Regular Expressions (JavaScript).sublime-syntax.json",
		build: (syntax) => convertSyntax(syntax),
	},
	{
		file: "regexp-python.tmLanguage.json",
		source: "Regular Expressions (Python).sublime-syntax.json",
		// VS Code's built-in Python grammar already uses `source.regexp.python`.
		build: (syntax) => convertSyntax(syntax, "source.regexp.py"),
	},
];

/* ---------------------------------------------------------------- generic */

function convertSyntax(syntax, scopeName = syntax.scope) {
	const repository = {};
	for (const [name, rules] of Object.entries(syntax.contexts)) {
		if (name !== "main") repository[name] = { patterns: convertRules(rules, name) };
	}
	return grammar(syntax, scopeName, convertRules(syntax.contexts.main, "main"), repository);
}

function convertRules(rules, where) {
	const out = [];
	for (const rule of rules) {
		if ("meta_scope" in rule || "meta_content_scope" in rule) continue;
		if ("include" in rule) {
			out.push({ include: rule.include === "main" ? "$self" : `#${rule.include}` });
		} else if (rule.push !== undefined) {
			out.push(convertPush(rule, where));
		} else if (rule.set !== undefined || rule.pop) {
			throw new Error(`${where}: "${rule.match}" uses ${rule.set ? "set" : "pop"} outside a pushed context`);
		} else {
			out.push(withCaptures({ match: rule.match, name: rule.scope }, "captures", rule.captures));
		}
	}
	return out;
}

/** A push of an anonymous context that has exactly one pop rule → begin/end. */
function convertPush(rule, where) {
	const context = rule.push;
	if (!Array.isArray(context) || typeof context[0] === "string") {
		throw new Error(`${where}: only anonymous single-context pushes can be converted`);
	}
	const pops = context.filter((r) => r.pop);
	if (pops.length !== 1 || context.some((r) => r.set !== undefined)) {
		throw new Error(`${where}: pushed context needs exactly one pop rule`);
	}
	const [pop] = pops;
	const meta = context.find((r) => "meta_scope" in r)?.meta_scope;
	const content = context.find((r) => "meta_content_scope" in r)?.meta_content_scope;
	const result = { begin: rule.match };
	withCaptures(result, "beginCaptures", rule.captures, rule.scope);
	result.end = pop.match;
	withCaptures(result, "endCaptures", pop.captures, pop.scope);
	if (meta) result.name = meta;
	if (content) result.contentName = content;
	result.patterns = convertRules(context.filter((r) => !r.pop), where);
	return result;
}

function withCaptures(target, key, captures, wholeScope) {
	const out = {};
	if (wholeScope) out[0] = { name: wholeScope };
	for (const [group, scope] of Object.entries(captures || {})) out[group] = { name: scope };
	if (Object.keys(out).length) target[key] = sortKeys(out);
	if (target.name === undefined) delete target.name;
	return target;
}

const sortKeys = (obj) =>
	Object.fromEntries(Object.entries(obj).sort(([a], [b]) => Number(a) - Number(b)));

function grammar(syntax, scopeName, patterns, repository) {
	return {
		$schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
		name: syntax.name,
		scopeName,
		comment: `Generated by scripts/build-grammars.mjs from sublime/ — do not edit.${syntax.comment ? ` ${syntax.comment}` : ""}`,
		patterns,
		repository,
	};
}

/* ------------------------------------------------------------------- PCRE */

/** Number of capturing groups in an Oniguruma pattern. */
function countGroups(source) {
	let count = 0;
	let inClass = false;
	for (let i = 0; i < source.length; i++) {
		const ch = source[i];
		if (ch === "\\") i++;
		else if (inClass) inClass = ch !== "]";
		else if (ch === "[") inClass = true;
		else if (ch === "(" && source[i + 1] !== "?") count++;
	}
	return count;
}

/**
 * Builds `{ regex, captures }` from parts. Each part is `[pattern, scope]`,
 * where scope is a string for the whole part or `{ 0: whole, n: inner-group }`.
 * Every part becomes a capture group; inner groups are renumbered to match.
 */
function seq(...parts) {
	let regex = "";
	const captures = {};
	let group = 0;
	for (const [pattern, scope] of parts) {
		const outer = ++group;
		regex += `(${pattern})`;
		const scopes = typeof scope === "string" ? { 0: scope } : scope || {};
		for (const [inner, name] of Object.entries(scopes)) {
			captures[Number(inner) === 0 ? outer : outer + Number(inner)] = { name };
		}
		group += countGroups(pattern);
	}
	return { regex, captures: sortKeys(captures) };
}

function pcreGrammar(syntax) {
	// Variables are inlined as non-capturing groups so capture numbers stay put.
	const vars = {};
	const expand = (source) =>
		source.replace(/\{\{(\w+)\}\}/g, (_, name) => {
			if (!(name in vars)) {
				const raw = syntax.variables[name];
				if (raw === undefined) throw new Error(`unknown variable ${name}`);
				vars[name] = `(?:${expand(raw).replace(/(?<!\\)\((?!\?)/g, "(?:")})`;
			}
			return vars[name];
		});
	const ctx = (name) => syntax.contexts[name];
	const matchOf = (name, index = 0) => ctx(name).filter((r) => "match" in r)[index].match;

	const GROUP = "keyword.control.group.regexp";
	const MODE = "storage.modifier.mode.regexp";
	const INVALID_QUANTIFIER = "invalid.illegal.unexpected-quantifier.regexp";
	// Sublime pushes `unexpected-quantifier-pop` after many tokens: any
	// quantifiers that directly follow are marked invalid.
	const QUANTIFIER = expand("(?:{{ranged_quantifier}}|{{character_quantifier}}){{lazy_or_possessive}}");
	const unexpected = [`(?:${QUANTIFIER})*`, INVALID_QUANTIFIER];

	const NAMED = { 0: "keyword.other.named-capture-group.regexp", ...nameCaptures("entity.name.capture-group.regexp") };
	const CONDITION = {
		0: "keyword.other.backref-and-recursion.conditional.regexp",
		...nameCaptures("variable.other.backref-and-recursion.regexp"),
		7: "variable.other.backref-and-recursion.regexp",
		8: "variable.other.backref-and-recursion.regexp",
		9: "variable.other.backref-and-recursion.regexp",
	};

	const body = (extended) => ({
		contentName: extended ? "meta.group.extended.regexp" : "meta.group.regexp",
		end: "\\)",
		endCaptures: { 0: { name: `${extended ? "meta.group.extended.regexp" : "meta.group.regexp"} ${GROUP}` } },
		patterns: [{ include: extended ? "#base-literal-extended" : "#base-literal" }],
	});
	// `(?x)`-style flags apply to the rest of the enclosing group.
	const rest = (extended) => ({
		end: "(?=\\))",
		patterns: [{ include: extended ? "#base-literal-extended" : "#base-literal" }],
	});
	const open = (meta, parts, then) => {
		const { regex, captures } = seq(["\\(", GROUP], ...parts);
		const rule = { begin: regex, beginCaptures: captures, ...then };
		return then.contentName ? { name: meta, ...rule } : prefixCaptures(rule, meta);
	};
	const single = (meta, parts) => {
		const { regex, captures } = seq(["\\(", GROUP], ...parts);
		return { match: regex, name: meta, captures };
	};

	// Mirrors group-start / group-start-extended, in the same order.
	const groupStart = (extended) => {
		const meta = extended ? "meta.group.extended.regexp" : "meta.group.regexp";
		const start = ctx(extended ? "group-start-extended" : "group-start").filter((r) => "match" in r);
		const m = (i) => start[i].match;
		return [
			open(meta, [[m(0), "constant.other.assertion.regexp"], unexpected], body(extended)),
			// Turns x mode on (normal) or off (extended) for the rest of the group.
			open(meta, [[m(1).replace(/\(\\\)\)$/, "").replace(/^\((.*)\)$/, "$1"), MODE], ["\\)", GROUP], unexpected], rest(!extended)),
			open(meta, [[m(2), MODE], unexpected], body(!extended)),
			open(meta, [[m(3), MODE], unexpected], body(extended)),
			open(meta, [[m(4), NAMED], unexpected], body(extended)),
			open(meta, [[m(5), CONDITION], unexpected], body(extended)),
			open(meta, [[m(6), "keyword.other.conditional.definition.regexp"], unexpected], body(extended)),
			// Condition is itself a group, e.g. (?(?=a)b|c); Sublime pushes no
			// unexpected-quantifier check here.
			open(meta, [[m(7), "keyword.other.conditional.regexp"]], body(extended)),
			{ include: "#group-start-common" },
			open(meta, [unexpected], body(extended)),
		];
	};

	const common = ctx("group-start-common").map((r) => r.match);
	const charsetRules = ctx("charset")[0].push;
	const charClass = (name) => charsetRules.find((r) => r.scope === name).match;

	const repository = {
		"base-literal": { patterns: [{ include: "#group" }, { include: "#base-common" }, { include: "#literal" }] },
		"base-literal-extended": {
			patterns: [
				{ include: "#group-extended" },
				{ include: "#extended-patterns" },
				{ include: "#base-common" },
				{ include: "#literal" },
			],
		},
		"base-common": {
			patterns: ["character-class", "special-escaped-char", "backslashes", "escaped-char", "charset", "operators"].map(
				(name) => ({ include: `#${name}` }),
			),
		},
		group: {
			patterns: [{ include: "#group-comment" }, { include: "#backtracking-control-verb" }, ...groupStart(false)],
		},
		"group-extended": {
			patterns: [{ include: "#group-comment" }, { include: "#backtracking-control-verb" }, ...groupStart(true)],
		},
		"group-start-common": {
			patterns: [
				single("meta.group.regexp", [[common[0].slice(1, common[0].indexOf(")(\\)")), MODE], ["\\)", GROUP]]),
				single("meta.group.regexp", [
					["\\?([+-]?\\d+)", { 0: "keyword.other.backref-and-recursion.regexp", 1: "variable.other.backref-and-recursion.regexp" }],
					["\\)", GROUP],
				]),
				single("meta.group.regexp", [
					["\\?&([\\w-]+)", { 0: "keyword.other.backref-and-recursion.regexp", 1: "variable.other.backref-and-recursion.regexp" }],
					["\\)", GROUP],
				]),
			],
		},
		"group-comment": {
			patterns: [
				{
					begin: matchOf("group-comment"),
					beginCaptures: { 0: { name: "punctuation.definition.comment.begin.regexp" } },
					end: "\\)",
					endCaptures: { 0: { name: "punctuation.definition.comment.end.regexp" } },
					name: "meta.group.regexp comment.block.group.regexp",
				},
			],
		},
		"backtracking-control-verb": {
			patterns: [{ match: matchOf("backtracking-control-verb"), name: "keyword.control.verb.regexp" }],
		},
		"character-class": {
			patterns: [{ match: expand(matchOf("character-class")), name: "keyword.control.character-class.regexp" }],
		},
		"special-escaped-char": {
			patterns: [
				{ match: expand("{{known_char_escape}}"), name: "constant.character.escape.regexp" },
				{ match: expand("{{invalid_char_escape}}"), name: "invalid.illegal.character.escape.regexp" },
			],
		},
		"escaped-char": { patterns: [{ match: expand("{{char_escape}}"), name: "constant.character.escape.regexp" }] },
		backslashes: {
			patterns: [
				tokenThenUnexpected(ctx("backslashes")[0].match, "keyword.control.anchors.regexp"),
				tokenThenUnexpected(ctx("backslashes")[1].match, "keyword.control.regexp"),
				withCaptures({ match: ctx("backslashes")[2].match, name: ctx("backslashes")[2].scope }, "captures", ctx("backslashes")[2].captures),
				withCaptures({ match: ctx("backslashes")[3].match, name: ctx("backslashes")[3].scope }, "captures", ctx("backslashes")[3].captures),
			],
		},
		operators: { patterns: [tokenThenUnexpected(matchOf("operators"), "keyword.operator.alternation.regexp")] },
		charset: {
			patterns: [
				{
					begin: ctx("charset")[0].match,
					beginCaptures: { 1: { name: "keyword.control.set.regexp" } },
					end: "\\]",
					endCaptures: { 0: { name: "keyword.control.set.regexp" } },
					name: "meta.set.regexp",
					patterns: [
						{ match: charClass("constant.other.posix-class.regexp"), name: "constant.other.posix-class.regexp" },
						range(),
						{ include: "#character-class" },
						{ include: "#special-escaped-char" },
						{ include: "#escaped-char" },
						{ include: "#charset" },
						{ match: "&&", name: "keyword.operator.intersection.regexp" },
					],
				},
			],
		},
		quantifiers: {
			patterns: ctx("quantifiers").map((r) => tokenThenUnexpected(expand(r.match), "keyword.operator.quantifier.regexp")),
		},
		literal: {
			patterns: [
				{ include: "#quantifiers" },
				...ctx("literal")
					.filter((r) => "match" in r)
					.map((r) => ({ match: r.match, name: r.scope })),
			],
		},
		"extended-patterns": {
			patterns: [
				{
					begin: "#",
					beginCaptures: { 0: { name: "punctuation.definition.comment.regexp" } },
					end: "\\n",
					name: "comment.line.number-sign.regexp",
				},
				{ match: "\\s+", name: "meta.ignored-whitespace.regexp" },
			],
		},
	};

	function tokenThenUnexpected(pattern, scope) {
		const { regex, captures } = seq([pattern, scope], unexpected);
		return { match: regex, captures };
	}

	// Sublime matches a range with a lookahead and two small contexts; here
	// it is a begin/end rule with the same alternatives, in the same order.
	// Its second context matches `-` before the range end, so extra dashes are
	// absorbed and the character after them ends the range (even `]`, or the
	// first character of the next line).
	function range() {
		const known = expand("{{known_char_escape}}");
		const invalid = expand("{{invalid_char_escape}}");
		const escape = expand("{{char_escape}}");
		const side = (plain) => `(?:(${known})|(${invalid})|(${escape})|${plain})`;
		const lookahead = expand("(?=(?:{{known_char_escape}}|{{char_escape}}|(?!\\\\-)[^\\]])-(?:{{known_char_escape}}|{{char_escape}}|[^\\]]))");
		const scopes = ["constant.character.escape.regexp", "invalid.illegal.character.escape.regexp", "constant.character.escape.regexp"];
		const captures = Object.fromEntries(scopes.map((name, i) => [i + 1, { name }]));
		return {
			begin: `${lookahead}${side("(?!\\\\-)[^\\]]")}-`,
			beginCaptures: captures,
			end: side("[^-\\n]"),
			endCaptures: captures,
			name: "constant.other.range.regexp",
			patterns: [{ match: "-" }],
		};
	}

	return grammar(
		syntax,
		syntax.scope,
		[
			// Sublime checks for unexpected quantifiers once, at the very start.
			{ match: `\\A(?:${QUANTIFIER})+`, name: INVALID_QUANTIFIER },
			{ include: "#base-literal" },
		],
		repository,
	);
}

function nameCaptures(nameScope) {
	return {
		1: "punctuation.definition.capture-group-name.begin.regexp",
		2: nameScope,
		3: "punctuation.definition.capture-group-name.end.regexp",
		4: "punctuation.definition.capture-group-name.begin.regexp",
		5: nameScope,
		6: "punctuation.definition.capture-group-name.end.regexp",
	};
}

// For the `x`-toggle groups the whole begin text keeps Sublime's meta scope
// without that scope leaking over the rest of the enclosing group.
function prefixCaptures(rule, meta) {
	const captures = {};
	for (const [group, { name }] of Object.entries(rule.beginCaptures)) captures[group] = { name: `${meta} ${name}` };
	return { ...rule, beginCaptures: captures };
}

/* ------------------------------------------------------------------ main */

export function buildAll() {
	return GRAMMARS.map(({ file, source, build }) => ({ file, json: `${JSON.stringify(build(readSyntax(source)), null, "\t")}\n` }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const check = process.argv.includes("--check");
	const outDir = path.join(root, "syntaxes");
	fs.mkdirSync(outDir, { recursive: true });
	let stale = false;
	for (const { file, json } of buildAll()) {
		const target = path.join(outDir, file);
		const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
		if (check) {
			if (current !== json) {
				console.error(`syntaxes/${file} is out of date; run npm run build`);
				stale = true;
			}
		} else if (current !== json) {
			fs.writeFileSync(target, json);
			console.log(`wrote syntaxes/${file}`);
		}
	}
	if (stale) process.exit(1);
}
